def rubros_disponibles() -> tuple[str, ...]:
    """Claves de rubro conocidas (para selector de onboarding, validación, etc.)."""
    return tuple(_RUBROS.keys())


def rubro_def(key: str | None) -> Rubro:
    """Definición del rubro; fail-safe a ``restaurante`` si es None o desconocido."""
    if key is None:
        return _RUBROS[RUBRO_DEFAULT]
    return _RUBROS.get(key, _RUBROS[RUBRO_DEFAULT])


def resolve_rubro(config: Mapping[str, Any] | None) -> str:
    """Resuelve la clave de rubro desde un ``config`` (dict) de tenant.

    Fail-safe: config vacío, sin clave ``rubro``, o con un rubro desconocido → ``restaurante``.
    """
    if not config:
        return RUBRO_DEFAULT
    key = config.get("rubro")
    if not isinstance(key, str) or key not in _RUBROS:
        return RUBRO_DEFAULT
    return key


def get_rubro(tenant: Any) -> str:
    """Clave de rubro de un tenant (duck-typing de ``tenant.config``)."""
    return resolve_rubro(getattr(tenant, "config", None))
