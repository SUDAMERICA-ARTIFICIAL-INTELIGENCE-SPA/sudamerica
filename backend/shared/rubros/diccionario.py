"""Diccionario de rubro (SSOT) — Fase 0 de la generalización multi-rubro de Sudamérica AI.

Única fuente de verdad del vocabulario, capacidades y categorías-semilla por tipo
de negocio. NO importa el ORM: ``get_rubro`` recibe el tenant por *duck-typing*
(``tenant.config``) para que el módulo sea puro y testeable sin base de datos.

Compatibilidad hacia atrás (guardrail): el rubro por defecto es ``restaurante`` y su
vocabulario/módulos reproducen el comportamiento actual. Un tenant sin ``rubro`` en su
``config`` (o con un rubro desconocido) se resuelve a ``restaurante`` de forma fail-safe,
por lo que el sistema existente no cambia.
"""

from __future__ import annotations

from dataclasses import dataclass
from types import MappingProxyType
from typing import Any, Mapping

RUBRO_DEFAULT = "restaurante"


class Primitiva:
    """Claves canónicas (internas, agnósticas de rubro) de las primitivas de negocio."""

    CATALOGO = "catalogo"
    ITEM = "item"
    CATEGORIA = "categoria"
    ORDEN = "orden"
    RECURSO = "recurso"
    AGENDA = "agenda"
    PARTE = "parte"  # cliente
    TRANSACCION = "transaccion"
    VARIANTE = "variante"
    EQUIPO = "equipo"
    METRICAS = "metricas"
    INGESTA = "ingesta"


PRIMITIVAS: tuple[str, ...] = (
    Primitiva.CATALOGO,
    Primitiva.ITEM,
    Primitiva.CATEGORIA,
    Primitiva.ORDEN,
    Primitiva.RECURSO,
    Primitiva.AGENDA,
    Primitiva.PARTE,
    Primitiva.TRANSACCION,
    Primitiva.VARIANTE,
    Primitiva.EQUIPO,
    Primitiva.METRICAS,
    Primitiva.INGESTA,
)


@dataclass(frozen=True)
class Rubro:
    """Definición inmutable de un rubro: vocabulario + capacidades + semillas."""

    key: str
    nombre: str
    emoji: str
    sector: str  # enlaza con lib/sector-config del front (KPIs/benchmarks)
    labels: Mapping[str, str]  # primitiva -> etiqueta visible (MappingProxyType)
    categorias_semilla: tuple[str, ...]
    # F6: etiqueta de la sub-entidad del cliente (Mascota/Vehículo/Propiedad/Paciente);
    # None ⟺ el rubro no incluye el módulo SUB_ENTIDAD (invariante testeada).
    sub_entidad_label: str | None = None
    # Categorización (ERP+CRM): subconjunto curado de CAPACIDADES en orden CAP_ORDER
    # (ver capacidades.py). Requerido de facto: la factory `_rubro` lo exige y los
    # tests fijan 100/100 no vacío.
    capacidades: tuple[str, ...] = ()
    # Flags de DATO sin capacidad de navegación (Etapa B — reemplazo de `modulos`):
    # gatean prompt/roles/UI como modos de operación, no vistas del sidebar.
    recurso: bool = False  # recurso físico reservable (Mesa/Silla/Bahía…)
    variantes: bool = True  # grupos de modificadores en el catálogo
    precio_medida: bool = False  # precio por peso/medida (kg, m², hora)

    def tiene_capacidad(self, capacidad: str) -> bool:
        return capacidad in self.capacidades

    def label(self, primitiva: str) -> str:
        return self.labels[primitiva]


def _rubro(
    *,
    key: str,
    nombre: str,
    emoji: str,
    sector: str,
    labels: dict[str, str],
    semillas: tuple[str, ...],
    capacidades: tuple[str, ...],
    sub_entidad_label: str | None = None,
    recurso: bool = False,
    variantes: bool = True,
    precio_medida: bool = False,
) -> Rubro:
    return Rubro(
        key=key,
        nombre=nombre,
        emoji=emoji,
        sector=sector,
        labels=MappingProxyType(dict(labels)),
        categorias_semilla=semillas,
        sub_entidad_label=sub_entidad_label,
        capacidades=capacidades,
        recurso=recurso,
        variantes=variantes,
        precio_medida=precio_medida,
    )


