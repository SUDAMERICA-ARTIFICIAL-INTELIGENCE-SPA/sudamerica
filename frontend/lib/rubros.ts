// Claves canónicas de las primitivas de negocio (internas, agnósticas de rubro).
export type Primitiva =
  | "catalogo"
  | "item"
  | "categoria"
  | "orden"
  | "recurso"
  | "agenda"
  | "parte"
  | "transaccion"
  | "variante"
  | "equipo"
  | "metricas"
  | "ingesta";

export const PRIMITIVAS: readonly Primitiva[] = [
  "catalogo",
  "item",
  "categoria",
  "orden",
  "recurso",
  "agenda",
  "parte",
  "transaccion",
  "variante",
  "equipo",
  "metricas",
  "ingesta",
] as const;

export interface RubroDef {
  key: RubroKey;
  nombre: string;
  emoji: string;
  sector: Sector; // enlaza con SECTOR_CONFIG (KPIs/benchmarks)
  labels: Record<Primitiva, string>;
  categoriasSemilla: readonly string[];
  /** F6: etiqueta de la sub-entidad del cliente (Mascota/Vehículo/…); label ⟹ capacidad expedientes. */
  subEntidadLabel?: string;
  /**
   * Categorización (ERP+CRM): subconjunto curado de CAPACIDADES en orden CAP_ORDER
   * (ver capacidades.ts). Requerido: los 100 rubros lo definen.
   */
  capacidades: readonly Capacidad[];
  // Flags de DATO sin capacidad de navegación (Etapa B — reemplazo de `modulos`):
  // gatean prompt/roles/UI como modos de operación, no vistas del sidebar.
  /** Recurso físico reservable (Mesa/Silla/Bahía…). Default false. */
  recurso?: boolean;
  /** Grupos de modificadores en el catálogo. Default true. */
  variantes?: boolean;
  /** Precio por peso/medida (kg, m², hora). Default false. */
  precioMedida?: boolean;
}

