function isRubroKey(value: string): value is RubroKey {
  return value in RUBROS;
}

/** Resuelve la clave de rubro desde el `config` del tenant; fail-safe a restaurante.
 * Acepta el `config` genérico del tenant (`Record<string, unknown>`) y estrecha con seguridad. */
export function resolveRubro(config: Record<string, unknown> | null | undefined): RubroKey {
  const key = config?.rubro;
  if (typeof key === "string" && isRubroKey(key)) {
    return key;
  }
  return RUBRO_DEFAULT;
}

/** Definición del rubro; fail-safe a restaurante si es null/desconocido. */
export function getRubroDef(key: string | null | undefined): RubroDef {
  if (typeof key === "string" && isRubroKey(key)) {
    return RUBROS[key];
  }
  return RUBROS[RUBRO_DEFAULT];
}

/** ¿El rubro tiene activa esta capacidad? */
export function tieneCapacidad(key: RubroKey, capacidad: Capacidad): boolean {
  return RUBROS[key].capacidades.includes(capacidad);
}

/** Pluraliza en español una etiqueta singular (Silla → Sillas, Cita → Citas). */
export function plural(word: string): string {
  if (!word) return word;
  const last = word.charAt(word.length - 1).toLowerCase();
  return "aeiouáéíóú".includes(last) ? `${word}s` : `${word}es`;
}

/** KPIs/benchmarks LATAM del rubro (reutiliza el mapa de sector-config). */
export function rubroSectorConfig(key: RubroKey): SectorConfig {
  return getSectorConfig(RUBROS[key].sector);
}

/** Opciones para el selector de rubro del onboarding. */
export const RUBRO_OPTIONS: readonly { value: RubroKey; label: string; emoji: string }[] = (
  Object.keys(RUBROS) as RubroKey[]
).map((key) => ({ value: key, label: RUBROS[key].nombre, emoji: RUBROS[key].emoji }));
